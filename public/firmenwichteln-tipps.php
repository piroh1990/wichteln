                <div class="highlight-box">
                    <h3>💰 Budget-Guidelines für Schweizer Firmen</h3>
                    <ul>
                        <li><strong>15-20 CHF:</strong> Ideal für grosse Teams (>20 Personen) oder kleinere Budgets</li>
                        <li><strong>20-30 CHF:</strong> Standard für mittlere Teams (10-20 Personen) – guter Mittelweg</li>
                        <li><strong>30-50 CHF:</strong> Für kleine Teams (<10 Personen) oder höhere Ansprüche</li>
                    </ul>
                    <p><strong>Wichtig:</strong> Das Budget sollte für alle Teilnehmer bezahlbar sein. Berücksichtigt unterschiedliche Gehaltsstufen!</p>
