            <section class="content-section">
                <h2>Beliebte Firmenwichteln-Varianten</h2>
                
                <h3>1. Klassisches Wichteln</h3>
                <p>Jeder zieht einen Namen und besorgt ein passendes Geschenk. Die Geschenke werden am Event persönlich überreicht.</p>
                <p><strong>Ideal für:</strong> Teams, die sich gut kennen und persönliche Geschenke schätzen.</p>
                
                <h3>2. Wichtel-Engel (Secret Santa)</h3>
                <p>Über 2-4 Wochen beschenkt ein "Wichtel-Engel" eine Person mit kleinen Aufmerksamkeiten am Schreibtisch – anonym. Am Schluss erfolgt die grosse Enthüllung.</p>
                <p><strong>Ideal für:</strong> Teams mit viel Kontakt im Büro. Budget: 5-10 CHF pro Woche.</p>
                
                <h3>3. Schrottwichteln</h3>
                <p>Jeder bringt ein ungeliebtes, skurriles oder lustiges Geschenk mit. Humor steht im Vordergrund!</p>
                <p><strong>Ideal für:</strong> Lockere Teams mit Sinn für Humor. Achtet darauf, dass es respektvoll bleibt.</p>
                
                <h3>4. Motto-Wichteln</h3>
                <p>Alle Geschenke folgen einem Thema: "Nachhaltig", "Regional", "Rot", "Selbstgemacht" etc.</p>
                <p><strong>Ideal für:</strong> Teams, die Wert auf spezielle Themen legen (z.B. Nachhaltigkeit).</p>
                
                <h3>5. Würfel-Wichteln</h3>
                <p>Alle Geschenke liegen in der Mitte. Reihum wird gewürfelt – bei einer 6 darf man sich ein Geschenk nehmen oder klauen.</p>
                <p><strong>Ideal für:</strong> Grosse Teams und gesellige Events mit genug Zeit.</p>
            </section>
            
