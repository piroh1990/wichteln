                <h2>Do's & Don'ts beim Firmenwichteln</h2>
                
                <div class="dos-donts">
                    <div class="do-box">
                        <h3>✅ DO's</h3>
                        <ul>
                            <li>Budget einhalten – Fairness ist wichtig</li>
                            <li>Geschenk schön verpacken</li>
                            <li>Neutrale Geschenke wählen (ausser ihr kennt euch gut)</li>
                            <li>Rechtszeitig besorgen (nicht last minute!)</li>
                            <li>Bei Unsicherheit: Klassiker wählen</li>
                            <li>Ausschlüsse nutzen (z.B. Vorgesetzte)</li>
                            <li>Spass haben und mitmachen!</li>
                        </ul>
                    </div>
                    
                    <div class="dont-box">
                        <h3>❌ DON'Ts</h3>
                        <ul>
                            <li>Budget massiv über-/unterschreiten</li>
                            <li>Geschenke mit politischen/religiösen Botschaften</li>
                            <li>Zu persönliche oder intime Geschenke</li>
                            <li>Alkohol (nur wenn ihr wisst, dass es passt)</li>
                            <li>Gebrauchte oder kaputte Sachen (ausser Schrottwichteln)</li>
                            <li>Geschenke mit Insider-Jokes, die nur 2 Personen verstehen</li>
                            <li>Sich selbst ziehen lassen</li>
