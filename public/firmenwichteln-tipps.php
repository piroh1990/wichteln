                <p>Eine gute Planung ist der Schlüssel zum erfolgreichen Firmenwichteln. Folge diesem bewährten 6-Schritte-Plan:</p>
                
                <div class="step-grid">
                    <div class="step-card">
                        <div class="step-number">1</div>
                        <h3>Team informieren</h3>
                        <p>Verschicke eine E-Mail oder Ankündigung mindestens 3-4 Wochen vor dem Event. Frage nach Interesse und erkläre das Konzept.</p>
