                <h2>Die Wichtel-Tradition</h2>
                <p>
                    <strong>Wichteln</strong> ist ein beliebter vorweihnachtlicher Brauch, bei dem sich Teilnehmer einer Gruppe gegenseitig kleine Geschenke machen. Der Clou: Jeder beschenkt nur eine Person, und die Zuordnung erfolgt per Los – oft anonym. Diese Tradition sorgt für Spannung, Freude und stärkt den Gemeinschaftssinn in Familien, Freundeskreisen und Unternehmen.
                </p>
                <p>
                    Der Name <strong>„Wichteln"</strong> leitet sich von den Wichteln ab – kleinen, geheimnisvollen Wesen aus der nordischen Mythologie, die heimlich Gutes tun. Genau wie diese kleinen Helfer überraschen auch die Wichtel-Teilnehmer einander mit durchdachten oder lustigen Geschenken.
                </p>
            </section>
            
            <section class="content-section">
                <h2>Woher kommt das Wichteln?</h2>
                <p>
                    Die Tradition des Wichtelns hat ihre Wurzeln in <strong>Skandinavien</strong>, wo sie unter dem Namen <strong>„Julklapp"</strong> bekannt ist. „Jul" bedeutet Weihnachten und „klapp" bezieht sich auf das Klopfen an der Tür, bevor das Geschenk heimlich ins Haus geworfen wird.
                </p>
                
                <div class="highlight-box">
                    <h3>📖 Historischer Hintergrund</h3>
                    <p>
                        Der Brauch verbreitete sich im 19. Jahrhundert von Skandinavien nach Deutschland und Österreich. Ursprünglich war es üblich, die Geschenke anonym an der Tür abzugeben – manchmal sogar durchs Fenster zu werfen! Heute wird das Wichteln meist in geselliger Runde zelebriert, wobei die Geschenke persönlich überreicht werden.
                    </p>
                </div>
            </section>
            
            <section class="content-section">
                <h2>Die klassischen Wichtel-Regeln</h2>
                <p>So funktioniert das traditionelle Wichteln in 5 einfachen Schritten:</p>
                
                <ol>
                    <li><strong>Gruppe bilden:</strong> Sammle alle Teilnehmer, die mitmachen möchten (mindestens 3 Personen)</li>
                    <li><strong>Budget festlegen:</strong> Einigt euch auf einen Höchstbetrag (z.B. 10-20 CHF)</li>
                    <li><strong>Namen ziehen:</strong> Jeder zieht einen Namen per Los und behält ihn geheim</li>
                    <li><strong>Geschenk besorgen:</strong> Kaufe oder bastle ein passendes Geschenk für deine gezogene Person</li>
                    <li><strong>Bescherung:</strong> Überreicht die Geschenke bei eurem Wichtel-Event</li>
                </ol>
                
