                <h2>Popular company Secret Santa variants</h2>
                
                <h3>1. Classic Secret Santa</h3>
                <p>Each person draws a name and finds a suitable gift. The gifts are handed over in person at the event.</p>
                <p><strong>Best for:</strong> teams that know each other well and appreciate personal gifts.</p>
                
                <h3>2. Secret Santa angel</h3>
                <p>For 2 to 4 weeks, someone leaves small treats on a colleague’s desk, in secret. The big reveal comes at the end.</p>
                <p><strong>Best for:</strong> teams that see a lot of each other in the office. Budget: 5-10 CHF per week.</p>
                
                <h3>3. Gag-gift Secret Santa</h3>
                <p>Everyone brings an unwanted, quirky or funny gift. Humour comes first!</p>
                <p><strong>Best for:</strong> relaxed teams with a sense of humour. Keep it respectful.</p>
                
                <h3>4. Themed Secret Santa</h3>
                <p>Every gift follows a theme: “sustainable”, “local”, “red”, “handmade”, and so on.</p>
                <p><strong>Best for:</strong> teams that care about a particular theme, such as sustainability.</p>
                
                <h3>5. Dice Secret Santa</h3>
                <p>All the gifts sit in the middle. People take turns rolling the dice. On a 6, you may take a gift or steal one.</p>
                <p><strong>Best for:</strong> large teams and sociable events when you have enough time.</p>
            </section>
            
