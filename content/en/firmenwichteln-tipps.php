                <h2>Do’s and don’ts for a company Secret Santa</h2>
                
                <div class="dos-donts">
                    <div class="do-box">
                        <h3>✅ Do</h3>
                        <ul>
                            <li>Stick to the budget — fairness matters</li>
                            <li>Wrap the gift nicely</li>
                            <li>Choose a neutral gift, unless you know each other well</li>
                            <li>Buy it in time, not at the last minute</li>
                            <li>If you are unsure, pick a classic</li>
                            <li>Use exclusions, for example for managers</li>
                            <li>Have fun and join in!</li>
                        </ul>
                    </div>
                    
                    <div class="dont-box">
                        <h3>❌ Don’t</h3>
                        <ul>
                            <li>Go far over or far under the budget</li>
                            <li>Give gifts with a political or religious message</li>
                            <li>Give gifts that are too personal or intimate</li>
                            <li>Give alcohol, unless you know it is welcome</li>
                            <li>Give used or broken items, except in a gag-gift exchange</li>
                            <li>Give gifts with an in-joke only two people understand</li>
                            <li>Draw yourself</li>
