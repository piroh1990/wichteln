                <h2>L’organisation, étape par étape</h2>
                <p>Une bonne préparation est la clé d’un Secret Santa en entreprise réussi. Suis ce plan en 6 étapes, éprouvé :</p>
                
                <div class="step-grid">
                    <div class="step-card">
                        <div class="step-number">1</div>
                        <h3>Informer l’équipe</h3>
                        <p>Envoie un e-mail ou une annonce au moins 3 à 4 semaines avant l’événement. Demande qui est intéressé et explique le principe.</p>
                    </div>
                    
                    <div class="step-card">
                        <div class="step-number">2</div>
                        <h3>Fixer les règles</h3>
                        <p>Fixe avec l’équipe : le budget (15-30 CHF recommandés), la date, la variante, et si les cadeaux restent anonymes.</p>
                    </div>
                    
                    <div class="step-card">
                        <div class="step-number">3</div>
                        <h3>Rassembler les participants</h3>
                        <p>Fais une liste avec le nom et l’adresse e-mail de chaque participant. En option : demande des envies ou des choses à éviter.</p>
                    </div>
                    
                    <div class="step-card">
                        <div class="step-number">4</div>
                        <h3>Tirer les noms</h3>
                        <p>Utilise un outil en ligne comme Wichtlä.ch. Ça fait gagner du temps, ça évite les erreurs, et personne ne se tire soi-même.</p>
                    </div>
                    
                    <div class="step-card">
                        <div class="step-number">5</div>
                        <h3>Envoyer un rappel</h3>
                        <p>1 à 2 semaines avant l’événement, envoie un rappel avec toutes les infos utiles : date, budget, déroulement.</p>
                    </div>
                    
                    <div class="step-card">
                        <div class="step-number">6</div>
                        <h3>Vivre l’événement</h3>
