                <h2>D’où vient le Secret Santa ?</h2>
                <p>
                    La tradition a ses racines en <strong>Scandinavie</strong>, où elle est connue sous le nom de <strong>« Julklapp »</strong>. « Jul » signifie Noël, et « klapp » renvoie au coup frappé à la porte avant de glisser le cadeau dans la maison, en secret.
                </p>
                
                <div class="highlight-box">
                    <h3>📖 Contexte historique</h3>
                    <p>
                        Au XIXe siècle, l’usage s’est répandu de la Scandinavie vers l’Allemagne et l’Autriche. À l’origine, on déposait les cadeaux anonymement devant la porte, parfois même en les lançant par la fenêtre ! Aujourd’hui, le Secret Santa se fête le plus souvent en groupe, et les cadeaux sont remis en personne. La révélation dit ensuite qui était le Père Noël secret de qui.
                    </p>
                </div>
            </section>
            
